export function ProgressRingSVG(progress, status) {
  const p = Math.min(100, Math.max(0, Number(progress) || 0));
  const r = 11;
  const c = 2 * Math.PI * r;
  const offset = c - (p / 100) * c;
  const col = status === 'read' ? 'var(--green)' : status === 'reading' ? 'var(--orange)' : 'var(--text-dim)';
  return `
    <svg class="rd-progress-ring" viewBox="0 0 28 28" width="22" height="22" aria-hidden="true">
      <circle class="ring-bg" cx="14" cy="14" r="${r}" fill="none" stroke="currentColor" stroke-width="2.5" opacity="0.18" />
      <circle class="ring-fill" cx="14" cy="14" r="${r}" fill="none" stroke="${col}" stroke-width="2.5"
              stroke-dasharray="${c.toFixed(2)}" stroke-dashoffset="${offset.toFixed(2)}" stroke-linecap="round"
              transform="rotate(-90 14 14)" />
    </svg>
  `;
}

export function ItemStripeColor(item, getGroupFn) {
  if (!item) return '';
  if (item.color) return item.color;
  const g = item.groupId && typeof getGroupFn === 'function' ? getGroupFn(item.groupId) : null;
  return g ? g.color : '';
}

