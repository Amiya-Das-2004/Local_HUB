export function esc(v) {
  return String(v === null || v === undefined ? '' : v)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;').replace(/'/g, '&#39;');
}

export function $(sel, parent) {
  return (parent || document).querySelector(sel);
}

export function $$(sel, parent) {
  return Array.from((parent || document).querySelectorAll(sel));
}

// Wrap occurrences of the active search query (already displayed as
// escaped HTML) in <mark> highlight tags.
export function Hl(escapedText, rawQuery) {
  const q = String(rawQuery || '').trim();
  if (!q) return escapedText;
  const eq = esc(q).replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  if (!eq) return escapedText;
  try {
    return escapedText.replace(new RegExp(eq, 'gi'), (m) => '<mark class="rd-hl">' + m + '</mark>');
  } catch (e) {
    return escapedText;
  }
}

export function uid(prefix) {
  return (prefix || 'id') + '_' + Date.now().toString(36) + Math.random().toString(36).slice(2, 7);
}

export async function copyText(text) {
  try {
    if (navigator.clipboard && navigator.clipboard.writeText) {
      await navigator.clipboard.writeText(text);
      return true;
    }
  } catch (e) { /* fallback below */ }
  try {
    const ta = document.createElement('textarea');
    ta.value = text;
    ta.style.position = 'fixed';
    ta.style.opacity = '0';
    document.body.appendChild(ta);
    ta.select();
    const ok = document.execCommand('copy');
    document.body.removeChild(ta);
    return ok;
  } catch (e) {
    return false;
  }
}

